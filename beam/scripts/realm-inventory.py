import difflib
from pathlib import Path
import re
import sys

BIFS = "erts/emulator/beam/bif.tab"
DIRTY = "erts/emulator/beam/erl_dirty_bif.tab"
MFA = re.compile(r"([a-z_0-9.']+):(.+)/(\d+)$")
DEFINITION = re.compile(r"\b(?:BIF_RETTYPE|Eterm)\s+(\w+)\s*\(\s*BIF_ALIST_\d+\s*\)"
                        r"(?:\s|/\*[\s\S]*?\*/)*\{")
